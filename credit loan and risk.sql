CREATE TABLE LOAN_CREDIT_RISK(
PERSON_AGE NUMBER,
PERSON_INCOME NUMBER,
PERSON_OWNERSHIP VARCHAR2(20),
EMP_LENTH NUMBER,
LOAN_INTENT VARCHAR2(30),
LOAN_GRADE VARCHAR2(5),
LOAN_AMOUNT NUMBER(12,2),
LOAN_INT_RATE NUMBER(10,00),
LOAN_STATUS NUMBER(1),
LOAN_PERCENT_INCOME NUMBER(8,4),
CB_PERSON_DEFAULT VARCHAR2(5),
CB_PERSON_CRED_HIST_LENGTH NUMBER);


 
SELECT * FROM  LOAN_CREDIT_RISK;

SELECT COUNT(*) AS TOTAL_RECORDS FROM LOAN_CREDIT_RIsk;

SELECT
LOAN_STATUS,COUNT(*)AS TOTAL_LOANS FROM  LOAN_CREDIT_RIsk
 GROUP BY LOAN_STATUS;
 
SELECT
  COUNT(*) AS TOTAL_LOANS,
  SUM(LOAN_STATUS)AS DEFAULT_LOANS,
  ROUND(SUM(LOAN_STATUS)*100.0/COUNT(*),2) AS DEFAULT_RATE_PERCENTAGE
FROM LOAN_CREDIT_RISK;



SELECT LOAN_INTENT,
    COUNT(*) AS TOTAL_LOANS,ROUND(
    SUM(LOAN_STATUS)*100.0/COUNT(*), 2) AS DEFAULT_RATE_PERCENTAGE FROM LOAN_CREDIT_RISK
    GROUP BY LOAN_INTENT
    ORDER BY DEFAULT_RATE_PERCENTAGE DESC;


SELECT 
     PERSON_OWNERSHIP,
     COUNT(*) AS TOTAL_LOANS,
     SUM(LOAN_STATUS) AS DEFAULT_LOANS,
     ROUND(SUM(LOAN_STATUS)*100.0/COUNT(*), 2) AS DEFAULT_RATE_PERCENTAGE
FROM  LOAN_CREDIT_RISK
GROUP BY PERSON_OWNERSHIP
ORDER BY DEFAULT_RATE_PERCENTAGE DESC;

SELECT 
     ROUND(AVG(PERSON_INCOME),2) AS AVG_ANNUAL_INCOME,
     ROUND(AVG(LOAN_AMOUNT),2)AS AVG_LOAN_AMOUNT,
     ROUND(AVG(LOAN_PERCENT_INCOME)*100,2) AS AVG_LOAN_TO_INCOME_PERCENT FROM LOAN_CREDIT_RISK;
     
     
     
SELECT LOAN_STATUS,
 COUNT(*) AS TOTAL_LOANS,
 ROUND(AVG(LOAN_INT_RATE),2 ) AS
 AVG_INTEREST_RATE
FROM  LOAN_CREDIT_RIsk
GROUP BY LOAN_STATUS
ORDER BY LOAN_STATUS;



SELECT
 LOAN_GRADE,
 COUNT(*) AS TOTAL_LOANS,ROUND(
 SUM(LOAN_STATUS)*100.0/COUNT(*),2)
 AS DEFAULT_RATE_PERCENTAGE
FROM  LOAN_CREDIT_RIsk
GROUP BY LOAN_GRADE
ORDER BY DEFAULT_RATE_PERCENTAGE DESC;


SELECT 
      CASE
        WHEN LOAN_PERCENT_INCOME >=0.40 THEN 'HIGH RISK'
        WHEN LOAN_PERCENT_INCOME >=0.20 THEN 'MEDIUM RISK'
        ELSE 'LOW RISK'
        END AS RISK_CATEGORY,
        COUNT(*) AS TOTAL_LOANS,
        SUM(LOAN_STATUS) AS DEFAULT_LOANS,
        ROUND(SUM(LOAN_STATUS)*100.0/COUNT(*),2) AS DEFAULT_RATE_PERCENTAGE 
FROM  LOAN_CREDIT_RIsk
GROUP BY 
        CASE
        WHEN LOAN_PERCENT_INCOME >=0.40 THEN 'HIGH RISK'
        WHEN LOAN_PERCENT_INCOME >=0.20 THEN 'MEDIUM RISK'
        ELSE 'LOW RISK'
        END 
    ORDER BY DEFAULT_RATE_PERCENTAGE DESC;













































